export const createTranslator = (lang) => {
  const translations = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  return (key, ...args) => {
    let str = translations[key] || key;
    args.forEach((arg, i) => {
      str = str.replace(`{${i}}`, arg);
    });
    return str;
  };
};
